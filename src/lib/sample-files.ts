import JSZip from 'jszip';
import { makePdf } from './pdf';
import { readFromStorage, saveNamedToStorage, storageExists } from './storage';
import type { ResourceItem } from './types';

/** Downloadable files for placeholder (seed) resources are generated on
 *  first request from the resource's own content, so downloads work end
 *  to end before any real files are uploaded. */
export async function ensureSampleFile(resource: ResourceItem, storageKey: string): Promise<Buffer | null> {
  if (!storageKey.startsWith('sample-')) return readFromStorage(storageKey);
  if (await storageExists(storageKey)) return readFromStorage(storageKey);

  const guideText = `${resource.title}\n\n${resource.shortDescription}\n\nPROMPT\n${resource.promptContent}\n\nSTEP-BY-STEP GUIDE\n${resource.instructions.map((s, i) => `${i + 1}. ${s.title}\n${s.body}`).join('\n\n')}\n\nNote: placeholder example content, supplied for library demonstration.`;
  let buffer: Buffer;
  if (storageKey.endsWith('.txt')) {
    buffer = Buffer.from(`${resource.title}\n\n${resource.promptContent}\n`, 'utf8');
  } else if (storageKey.endsWith('.pdf')) {
    buffer = makePdf(resource.title.replace(' — Placeholder Example', '').replace(' — Placeholder Guide', '').replace(' — Placeholder Workflow', '').replace(' — Placeholder Bundle', '').replace(' — Placeholder', ''), guideText);
  } else if (storageKey.endsWith('.zip')) {
    const zip = new JSZip();
    zip.file('prompt.txt', `${resource.title}\n\n${resource.promptContent}\n`);
    zip.file('guide.txt', guideText);
    zip.file('README.txt', 'Placeholder resource bundle generated by the library for demonstration.\nUpload the real bundle through the admin dashboard to replace it.');
    buffer = await zip.generateAsync({ type: 'nodebuffer' });
  } else {
    return null;
  }
  await saveNamedToStorage(buffer, storageKey);
  return buffer;
}

export function formatBytes(bytes: number): string {
  if (!bytes) return '—';
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}
